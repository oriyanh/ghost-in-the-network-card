def generate_pattern(rule, prefix_size, postfix_size):
    re_fmt = f"/sessionId={'.'*prefix_size}[{rule}]{'.'*postfix_size}/"
    return re_fmt

def generate_patterns(rules, match_length):
    subset_id = 1
    generated_rules = []
    for i in range(match_length):
        for j, rule in enumerate(rules):
            fmt = f"# Is byte {i}, bit {j} (MSB) turned on?\n"
            fmt += f"subset_id={subset_id}\n"
            prefix_size = i
            postfix_size = match_length - i - 1
            pattern = generate_pattern(rule, prefix_size, postfix_size)
            fmt += f"{subset_id}, {pattern}\n\n"
            generated_rules.append(fmt)
            subset_id += 1
    return generated_rules
